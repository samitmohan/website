import type { Metadata } from "next";
import Link from "next/link";
import { Figure } from "@/components/figure";
import { Mark } from "@/components/mark";
import { PublicNav, PublicFooter } from "@/components/public-nav";
import { RSS_ALTERNATE } from "@/lib/metadata";

export const metadata: Metadata = {
  alternates: { canonical: "/", types: RSS_ALTERNATE },
};

// Nothing here reads anything that can change between deploys.
export const revalidate = false;

/**
 * One screen, three doors: the name (about) and the two figures (blog,
 * projects), under one line saying what the work is. The argument for it is on
 * /about and the writing is on /blog.
 *
 * The gradient-descent figure hangs from the top edge rather than sitting in
 * the column: the drawing is a weight on a thread, so anywhere below the top of
 * the page it reads as hung from nothing.
 *
 * Server component, no client JS beyond the theme toggle. The figures animate
 * in CSS inside their own files.
 */
export default function HomePage() {
  return (
    <div className="home">
      <PublicNav />

      <Figure name="gradient-descent" className="home-hang accent-teal" />

      <main id="main" className="home-stage">
        {/* The page is a wordmark and three drawings, so there is no text to
            promote into a heading - and a page with no h1 announces nothing to
            a screen reader landing on it. */}
        <h1 className="sr-only">Samit Mohan</h1>

        {/* accent-teal because the wordmark is the door to /about, the same
            way each figure below carries the accent of the page it opens. */}
        <Link
          href="/about"
          className="wordmark rise-in accent-teal"
          aria-label="About"
        >
          <span className="wordmark-word">
            samit
            {/* Generated by scripts/gen-rough.mjs. Draws itself left to right
                on hover - the gesture the wordmark used to make by scaling
                itself 11% on a bezier that overshoots past 1. */}
            <Figure name="rough/underline" className="wordmark-rule" />
          </span>
          <Mark name="computer" ext="png" className="wordmark-computer" />
        </Link>

        {/* The page was a name and two drawings, with no answer to the only
            question a first-time visitor has. The role and the employer are
            not that answer - they are on /about, one click away, and they date
            the page. What the work is does not. */}
        <p className="home-line">
          I rebuild ML from scratch and write about it.
        </p>
      </main>

      {/* Each door owns an accent, so its figure and its caption are drawn in
          the colour the destination page is built in. The label is a caption
          under the drawing rather than a tile that rises on hover: a hover
          label is no label at all on a touch screen, and it hid the only text
          that said which drawing was the blog. */}
      <div className="home-doors">
        <Link href="/blog" className="door door-blog accent-blue">
          <Figure name="blog-backprop" className="door-figure" />
          <span className="door-label">Blog</span>
        </Link>
        <Link href="/projects" className="door door-projects accent-crimson">
          <Figure name="agent-loop" className="door-figure" />
          <span className="door-label">Projects</span>
        </Link>
      </div>

      <PublicFooter />
    </div>
  );
}
